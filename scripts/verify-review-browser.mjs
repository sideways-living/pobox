import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
if (!process.env.REVIEW_SESSION) throw new Error("Start the isolated reviewBrowserServer fixture and provide REVIEW_SESSION.");
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: "pobox_watch_session", value: process.env.REVIEW_SESSION, url: "http://127.0.0.1:4189" }]);
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  // Authentication is fixture-only; all review/dashboard requests use the real local API.
  await page.route("**/api/v1/auth/login", (route) => route.fulfill({ json: { ok: true } }));
  await page.goto("http://127.0.0.1:4189");
  await page.getByRole("button", { name: "Use Password to Set Up Security" }).click();
  await page.getByLabel("Email", { exact: true }).fill("daniel@example.com");
  await page.getByLabel("Password", { exact: true }).fill("fixture");
  await page.getByRole("button", { name: "Continue with Password" }).click();
  await page.getByRole("button", { name: "Got It" }).click();
  await page.getByRole("button", { name: "Needs Review", exact: true }).click();
  await page.locator(".review-item").first().waitFor();
  assert.equal(await page.locator(".review-item").count(), 3);
  const missing = page.locator(".review-item").filter({ hasText: "Mail2Day: PO Box 3020" });
  assert.match(await missing.innerText(), /Received/);
  assert.match(await missing.innerText(), /notice@example.test/);
  assert.match(await missing.innerText(), /Please collect your item/);
  await page.screenshot({ path: "/tmp/pobox-review-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "/tmp/pobox-review-mobile.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, "Mobile content must not overflow");
  await page.setViewportSize({ width: 1440, height: 1000 });
  const officeId = await missing.getByLabel("Create missing PO box").locator("option").nth(1).getAttribute("value");
  await missing.getByLabel("Create missing PO box").selectOption(officeId);
  await missing.getByRole("button", { name: "Create and Mark Waiting" }).click();
  await missing.waitFor({ state: "detached" });
  const match = page.locator(".review-item").filter({ hasText: "Unclear parcel notification" });
  assert.equal(await match.getByLabel("Match existing PO box").inputValue(), "");
  await match.getByLabel("Match existing PO box").selectOption("box_1234");
  await page.route("**/review-items/*/resolve", (route) => route.fulfill({ status: 503, json: { error: "Temporary review failure" } }), { times: 1 });
  await match.getByRole("button", { name: "Match and Mark Waiting" }).click();
  await match.getByRole("alert").waitFor();
  assert.match(await match.getByRole("alert").innerText(), /Temporary review failure/);
  await match.getByRole("button", { name: "Match and Mark Waiting" }).click();
  await match.waitFor({ state: "detached" });
  const ignored = page.locator(".review-item").filter({ hasText: "Promotional newsletter" });
  page.once("dialog", (dialog) => dialog.dismiss());
  await ignored.getByRole("button", { name: "Mark Ignored" }).click();
  assert.equal(await ignored.count(), 1);
  page.once("dialog", (dialog) => dialog.accept());
  await ignored.getByRole("button", { name: "Mark Ignored" }).click();
  await ignored.waitFor({ state: "detached" });
  assert.match(await page.locator("main").innerText(), /No mail notifications need manual review/);
  assert.deepEqual(errors, []);
  console.log("PASS: desktop/mobile layout, details, atomic create, existing match, ignore cancellation/confirmation, empty state; no browser errors.");
} finally { await browser.close(); }
