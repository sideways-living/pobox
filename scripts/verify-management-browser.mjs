import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
if (!process.env.REVIEW_SESSION) throw new Error("Provide the isolated reviewBrowserServer session.");
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: "pobox_watch_session", value: process.env.REVIEW_SESSION, url: "http://127.0.0.1:4189" }]);
  const page = await context.newPage();
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.route("**/api/v1/auth/login", (route) => route.fulfill({ json: { ok: true } }));
  // Directory transport is a deterministic fixture; ranking is tested separately.
  await page.route("**/post-office-locations/search?*", async (route) => {
    const query = new URL(route.request().url()).searchParams.get("query");
    if (query === "old") await new Promise((resolve) => setTimeout(resolve, 700));
    await route.fulfill({ json: [{ sourceId: "fixture", name: query === "old" ? "Stale Office" : "South Test LPO", address: "181 Clarendon Street, South Melbourne VIC 3205", phone: "+61 3 9000 1111", latitude: -37.832, longitude: 144.96, suburb: "South Melbourne", state: "VIC", postcode: "3205" }] });
  });
  await page.goto("http://127.0.0.1:4189");
  await page.getByRole("button", { name: "Use Password to Set Up Security" }).click();
  await page.getByLabel("Email", { exact: true }).fill("daniel@example.com");
  await page.getByLabel("Password", { exact: true }).fill("fixture");
  await page.getByRole("button", { name: "Continue with Password" }).click();
  await page.getByRole("button", { name: "Got It" }).click();
  await page.getByRole("button", { name: "Post Offices", exact: true }).click();
  const waiting = page.locator(".mailbox-row").filter({ hasText: "PO Box 1234" });
  assert.match(await waiting.innerText(), /Mail and parcel waiting/);
  assert.match(await waiting.innerText(), /Parcel Detected/);
  await waiting.getByRole("button", { name: "Mark Collected" }).click();
  await waiting.getByText(/Collected/).waitFor();
  assert.doesNotMatch(await waiting.innerText(), /Detected/);
  const add = page.locator("section.panel").filter({ has: page.getByRole("heading", { name: "Add Post Office", exact: true }) });
  const search = add.getByLabel("Search suburb, postcode, post office name, or street");
  await search.fill("old");
  await page.waitForRequest("**/post-office-locations/search?*");
  await search.fill("south");
  await add.getByRole("button", { name: /South Test LPO/ }).click();
  await page.waitForTimeout(800);
  assert.equal(await add.getByRole("button", { name: /Stale Office/ }).count(), 0);
  assert.equal(await add.getByLabel("Address", { exact: true }).inputValue(), "181 Clarendon Street, South Melbourne VIC 3205");
  assert.equal(await add.getByLabel("Latitude", { exact: true }).inputValue(), "-37.832");
  assert.equal(await add.getByLabel("Longitude", { exact: true }).inputValue(), "144.96");
  assert.equal(await add.getByLabel("Phone", { exact: true }).inputValue(), "+61 3 9000 1111");
  await add.getByRole("button", { name: "Create Post Office" }).click();
  const office = page.getByRole("article", { name: "South Test LPO", exact: true });
  await office.waitFor();
  const boxes = page.locator("section.panel").filter({ has: page.getByRole("heading", { name: "Add PO Box", exact: true }) });
  await boxes.getByRole("combobox").selectOption({ label: "South Test LPO" });
  for (const number of ["501", "502"]) {
    await boxes.getByLabel("PO Box Number", { exact: true }).fill(number);
    await boxes.getByRole("button", { name: "Create PO Box" }).click();
    await office.getByText(`PO Box ${number}`, { exact: true }).waitFor();
  }
  await boxes.getByLabel("PO Box Number", { exact: true }).fill("501");
  assert.equal(await boxes.getByRole("button", { name: "Create PO Box" }).isDisabled(), true);
  await office.locator(".mailbox-row").filter({ hasText: "PO Box 502" }).getByTitle("Edit PO box", { exact: true }).click();
  const boxEdit = office.locator("form.mailbox-row");
  await boxEdit.getByLabel("PO Box Number").fill("503");
  await office.getByTitle("Edit post office", { exact: true }).click();
  await office.getByLabel("Phone", { exact: true }).fill("");
  await page.screenshot({ path: "/tmp/pobox-management-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "/tmp/pobox-management-mobile.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await boxEdit.getByRole("button", { name: "Save", exact: true }).click();
  await office.getByText("PO Box 503", { exact: true }).waitFor();
  await page.route("**/post-offices/*", (route) => route.fulfill({ status: 503, json: { error: "Temporary save failure" } }), { times: 1 });
  await office.getByRole("button", { name: "Save", exact: true }).click();
  await page.getByText("Temporary save failure", { exact: true }).waitFor();
  assert.equal(await office.getByLabel("Phone", { exact: true }).count(), 1);
  await office.getByRole("button", { name: "Save", exact: true }).click();
  await office.getByTitle("Edit post office", { exact: true }).waitFor();
  page.once("dialog", (dialog) => dialog.dismiss());
  await office.getByTitle("Delete post office", { exact: true }).click();
  assert.equal(await office.count(), 1);
  page.once("dialog", (dialog) => { assert.match(dialog.message(), /History.*Pending review/); return dialog.accept(); });
  await office.getByTitle("Delete post office", { exact: true }).click();
  await office.waitFor({ state: "detached" });
  await page.getByRole("button", { name: "Team", exact: true }).click();
  const directory = page.locator("section.panel").filter({ has: page.getByRole("heading", { name: "Team Directory", exact: true }) });
  const deleted = page.locator("section.panel").filter({ has: page.getByRole("heading", { name: "Deleted Users", exact: true }) });
  const john = directory.locator(".team-member").filter({ hasText: "john@example.com" });
  page.once("dialog", dialog => dialog.dismiss());
  await john.getByTitle("Delete user access", { exact: true }).click();
  assert.equal(await john.count(), 1);
  page.once("dialog", dialog => dialog.accept());
  await john.getByTitle("Delete user access", { exact: true }).click();
  await deleted.getByText("john@example.com", { exact: true }).waitFor();
  assert.equal(await john.count(), 0);
  assert.equal(await deleted.getByRole("button").count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: "/tmp/pobox-deleted-users-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: "/tmp/pobox-deleted-users-desktop.png", fullPage: true });
  assert.deepEqual(errors, []);
  console.log("PASS: directory population and stale responses, multiple boxes, duplicate validation, collection timestamp, responsive edits, failure/retry, archive confirmation.");
} finally { await browser.close(); }
