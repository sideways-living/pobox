import assert from "node:assert/strict";
import { currentTotpCode } from "../server/dist/src/auth/totp.js";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const cdp = await context.newCDPSession(page);
  await cdp.send("WebAuthn.enable");
  await cdp.send("WebAuthn.addVirtualAuthenticator", { options: { protocol: "ctap2", transport: "internal", hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } });
  await page.goto("http://localhost:4190/?email=daniel%40example.com");
  assert.equal(await page.getByLabel("Email", { exact: true }).inputValue(), "daniel@example.com");
  assert.equal(await page.getByLabel("Password", { exact: true }).count(), 0);
  await page.getByRole("button", { name: "Use Password to Set Up Security" }).click();
  await page.getByLabel("Password", { exact: true }).fill("Password123!");
  await page.getByRole("button", { name: "Continue with Password" }).click();
  await page.getByText("Finish securing your account", { exact: true }).waitFor();
  assert.equal((await context.request.get("http://localhost:4190/api/v1/workspaces/ws_company/dashboard")).status(), 403);
  await page.getByRole("button", { name: "Add Passkey", exact: true }).click();
  await page.locator(".setup-step.complete").waitFor();
  await page.getByRole("button", { name: "Set Up Authenticator App" }).click();
  const secret = await page.getByLabel("Manual setup key").inputValue();
  await page.getByLabel("Six-digit code").fill(currentTotpCode(secret));
  await page.getByRole("button", { name: "Confirm 2FA" }).click();
  await page.locator(".recovery-codes code").waitFor();
  const codes = (await page.locator(".recovery-codes code").innerText()).split("\n");
  await page.getByRole("button", { name: "Continue to pobox.watch" }).click();
  await page.getByRole("button", { name: "Got It" }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByLabel("Current authenticator or unused recovery code").fill(codes[0]);
  await page.getByRole("button", { name: "Replace Authenticator" }).click();
  const replacement = await page.getByLabel("Manual setup key").inputValue();
  await page.getByLabel("Six-digit code").fill(currentTotpCode(replacement));
  await page.getByRole("button", { name: "Confirm 2FA" }).click();
  await page.locator(".recovery-codes code").waitFor();
  const newCodes = (await page.locator(".recovery-codes code").innerText()).split("\n");
  await page.screenshot({ path: "/tmp/pobox-security-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "/tmp/pobox-security-mobile.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  // Exercise the real logout endpoint and copied-cookie rejection.
  const oldCookies = await context.cookies();
  await context.request.post("http://localhost:4190/api/v1/auth/logout");
  const copied = await browser.newContext();
  await copied.addCookies(oldCookies);
  assert.equal((await copied.request.get("http://localhost:4190/api/v1/workspaces/ws_company/dashboard")).status(), 401);
  await copied.close();
  await page.reload();
  await page.getByRole("button", { name: "Continue with Passkey" }).click();
  await page.getByLabel("Authenticator or recovery code").fill(newCodes[0]);
  await page.getByRole("button", { name: "Verify Code" }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log("PASS: email prefill, passkey-first/password fallback, real WebAuthn enrolment and authentication, mandatory gate, recovery replacement, logout revocation, mobile overflow.");
} finally { await browser.close(); }
